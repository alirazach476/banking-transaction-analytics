import React from "react";
import { useApi, useRange, useTheme } from "../lib/context.jsx";
import { apiKey } from "../lib/api.js";
import { date, int } from "../lib/format.js";
import { Card, DomainBadge, ErrorState, PageHeader, Segmented, Skeleton } from "../ui/kit.jsx";

export default function Settings() {
  const { theme, setTheme } = useTheme();
  const { from, to } = useRange();
  const meta = useApi("/v1/meta");
  return (
    <>
      <PageHeader title="Settings & methodology" subtitle="Appearance, session, data domains and the definition of every headline metric." />
      <div className="grid g-2 mb">
        <Card style={{ padding: 18 }}>
          <h3>Appearance</h3>
          <p style={{ color: "var(--text-2)" }}>Theme (remembered in this browser).</p>
          <Segmented label="Theme" value={theme} onChange={setTheme} options={[{ value: "dark", label: "Dark" }, { value: "light", label: "Light" }]} />
          <h3 style={{ marginTop: 20 }}>Session</h3>
          <p style={{ color: "var(--text-2)", margin: "6px 0" }}>Date range: <b>{date(from)}</b> to <b>{date(to)}</b> (kept in the URL so views can be shared).</p>
          <p style={{ color: "var(--text-2)", margin: "6px 0" }}>API access: <b>{apiKey() ? "X-API-Key set for this browser session" : "no key (local development)"}</b>{meta.data ? ` · server authentication: ${meta.data.auth}` : ""}. The key is read from <code>?key=</code>, held in sessionStorage only and never written to the page.</p>
        </Card>
        <Card style={{ padding: 18 }}>
          <h3>Data domains</h3>
          {meta.isPending ? <Skeleton h={160} /> : meta.isError ? <ErrorState error={meta.error} onRetry={() => meta.refetch()} /> : (
            <>
              <div style={{ display: "grid", gap: 10, marginTop: 8 }}>
                {Object.entries(meta.data.domains).map(([k, d]) => (
                  <div key={k} style={{ display: "flex", gap: 10, alignItems: "center", flexWrap: "wrap" }}>
                    <DomainBadge kind={d.kind} label={d.kind} /><b>{d.label}</b>
                    <span style={{ color: "var(--muted)", fontSize: 12 }}>{d.n != null ? `${int(d.n)} rows` : ""}{d.d0 ? ` · ${d.d0} to ${d.d1}` : ""}</span>
                  </div>))}
              </div>
              <p style={{ color: "var(--text-2)", marginTop: 12 }}>{meta.data.currency_note}</p>
              <p style={{ color: "var(--muted)", fontSize: 12 }}>Synthetic = generated by the project's simulator (no real customers). Real = published aggregate statistics. Simulated = model results on simulated data. Real and synthetic data are never mixed in one metric.</p>
            </>)}
        </Card>
      </div>
      <Card style={{ padding: 18 }}>
        <h3 style={{ marginBottom: 10 }}>Metric definitions</h3>
        {meta.data && <dl style={{ display: "grid", gridTemplateColumns: "minmax(160px,220px) 1fr", gap: "10px 18px", margin: 0 }} data-testid="definitions">
          {Object.entries(meta.data.definitions).map(([k, v]) => <React.Fragment key={k}><dt style={{ fontWeight: 600 }}>{k.replace(/_/g, " ")}</dt><dd style={{ margin: 0, color: "var(--text-2)" }}>{v}</dd></React.Fragment>)}
        </dl>}
      </Card>
    </>
  );
}
